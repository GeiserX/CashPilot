"""Scaffold a new service from its YAML (CashPilot-9q1).

Adding a service should be one file plus an optional collector. It currently
also means a README table row and a docs/guides page, and every extra place a
contributor has to remember is a place a first-time contributor gets it wrong,
picks up a review comment, and does not come back.

The README half is generated by generate_readme_tables.py. This writes the
guide stub from the same YAML, so the only handwritten thing left is the prose
that genuinely needs a human.
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path
from urllib.parse import urlsplit

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from app import catalog  # noqa: E402

TEMPLATE = """# {name}

> **Category:** {category} | **Status:** {status}
>
> **Website:** [{website_label}]({header_url}){header_note}

## Description

{description}

## Earning Estimates

| Metric | Value |
|--------|-------|
| Monthly range | {earnings} |
| Payout methods | {methods} |
| Minimum payout | {minimum} |

## Requirements

| Requirement | Value |
|-------------|-------|
| Residential IP required | {residential} |
| VPS allowed | {vps} |
| Devices per account | {per_account} |
| Devices per IP | {per_ip} |

## Setup

1. Sign up at [{name}]({signup}).{referral_note}
2. Copy the credentials listed in the service's catalog entry.
3. Deploy from the CashPilot catalog and paste them when prompted.

<!-- Everything above is derived from services/{category}/{slug}.yml.
     Add anything a user genuinely needs a human to explain BELOW this line:
     captcha quirks, account gotchas, what the dashboard calls things. -->
"""


def _fmt(value: object, unknown: str = "Not documented") -> str:
    if value is None:
        return unknown
    if isinstance(value, bool):
        return "Yes" if value else "No"
    if value == 0:
        return "Unlimited"
    return str(value)


def referral_note(service: dict) -> str:
    """The line that sits under a guide's signup link when that link is a referral.

    Smaller than the text around it, but next to the link, so the reader learns
    it before the click. Empty when the catalog has no referral code: a bare
    signup URL is not a referral link. tests/test_referral_disclosure.py checks
    every guide against it.
    """
    ref = service.get("referral") or {}
    if not ref.get("code") or not ref.get("signup_url"):
        return ""
    note = "Referral link: the CashPilot maintainer may earn a commission from it."
    return f"<small>{note}</small>"


def code_entry_note(service: dict) -> str:
    """The line that tells a guide reader to type the code, when the link does not carry it.

    Empty unless the catalog sets referral.code_entry: some signups (a browser
    extension, a form that ignores the URL) never read the code from the link,
    and a reader who only clicks it credits nobody.
    """
    ref = service.get("referral") or {}
    if not referral_note(service) or not ref.get("code_entry"):
        return ""
    return f"When the signup asks for a referral code, type `{ref['code_entry']}`: the link does not fill it in."


def render(slug: str) -> str:
    service = catalog.get_service(slug)
    if not service:
        raise SystemExit(f"No catalog entry for {slug!r}. Write services/<category>/{slug}.yml first.")
    reqs = service.get("requirements") or {}
    earnings = service.get("earnings") or {}
    payment = service.get("payment") or {}
    low, high = earnings.get("monthly_low"), earnings.get("monthly_high")
    website = service.get("website", "")
    signup = (service.get("referral") or {}).get("signup_url") or website
    note = referral_note(service)
    typed = code_entry_note(service)
    return TEMPLATE.format(
        name=service.get("name", slug),
        slug=slug,
        category=service.get("category", ""),
        status=str(service.get("status", "")).title(),
        # A referral service's header links its coded signup, with the note under
        # it: a bare homepage link at the top of the page is a signup that pays
        # nobody (tests/test_referral_disclosure.py fails a guide that has one).
        website_label=(urlsplit(website).hostname or website).removeprefix("www."),
        header_url=signup if note else website,
        header_note=(f"\n>\n> {note}" if note else "") + (f"\n>\n> {typed}" if typed else ""),
        description=service.get("description", "").strip(),
        earnings=(f"${low} - ${high} (estimate)" if low is not None and high is not None else "Not documented"),
        methods=", ".join(payment.get("methods") or []) or "Not documented",
        minimum=_fmt(payment.get("minimum_payout")),
        residential=_fmt(reqs.get("residential_ip")),
        vps=_fmt(reqs.get("vps_ip")),
        per_account=_fmt(reqs.get("devices_per_account")),
        per_ip=_fmt(reqs.get("devices_per_ip")),
        signup=signup,
        referral_note=f"\n\n    {note}\n" if note else "",
    )


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("slug")
    parser.add_argument("--force", action="store_true", help="overwrite an existing guide")
    args = parser.parse_args()

    target = ROOT / "docs" / "guides" / f"{args.slug}.md"
    if target.exists() and not args.force:
        print(f"{target} already exists; pass --force to overwrite.", file=sys.stderr)
        return 1
    target.write_text(render(args.slug), encoding="utf-8")
    print(f"Wrote {target}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
